export function mediaLabel(fileName) {
  return fileName
    .replace(/\.[^.]+$/, "")
    .trim()
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

